/**
 * Generated images (#79) — where the bytes live, and how they reach other
 * devices.
 *
 * A chat message never carries the picture itself. The chat is one
 * E2E-encrypted blob per session that is re-pushed whole on every change; a
 * 1–2 MB base64 image inside it would be re-uploaded with every later
 * keystroke of that chat and re-decrypted on every open. So the message holds
 * a small REFERENCE, and the bytes go where document originals already go:
 *
 * - **locally** into the sealed IndexedDB store "images" (same mechanism as
 *   "originals" — encrypted at rest by the local cache layer);
 * - **cross-device** as encrypted chunks in the `originals` sync collection,
 *   under an `img:` id prefix, sealed with the originals key. Fire-and-forget
 *   after the local store; a device that has the reference but not the bytes
 *   fetches and reassembles them lazily when the message is rendered.
 *
 * Zero-knowledge holds: the image is generated by the provider from a prompt
 * that was scrubbed like any text; from the moment it lands here it is only
 * ever stored or transported encrypted.
 */

import { syncApi } from "@/lib/api/syncApi";
import { getMasterKey } from "@/lib/authStore";
import {
  base64ToBytes,
  bytesToBase64,
  decryptBytes,
  deriveOriginalsKey,
  encryptBytes,
} from "@/lib/crypto/quonCrypto";
import { idbDelete, idbGetBytes, idbPutBytes } from "@/lib/idbStore";

import { assembleChunks, chunkBytes, ORIGINALS_COLLECTION } from "../documents/originalChunks";

/** Standard base64 → bytes via the platform decoder. The crypto module's
 *  base64ToBytes is libsodium's (URL-safe variant, needs the WASM ready) —
 *  wrong tool for a provider's plain data URL, and it is what made the first
 *  version return null for every image in the unit environment. */
function decodeStdBase64(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

const IDB = "images" as const;
/** Generated images share the originals collection; the prefix keeps the id
 *  space apart from document ids (`<docId>:<n>`). */
const ID_PREFIX = "img:";
/** A generated image larger than this is not stored — the provider limits are
 *  far below it; the cap only guards against a runaway payload. */
export const MAX_IMAGE_BYTES = 12 * 1024 * 1024;

/** What a chat message keeps: enough to load or fetch the bytes, never the bytes. */
export interface GeneratedImageRef {
  id: string;
  mime: string;
  size: number;
  /** Set once the encrypted chunks are on the server (cross-device). Absent =
   *  only this device has the bytes (upload pending, or failed). */
  chunkCount?: number;
}

/** `data:image/png;base64,…` → { mime, bytes }. Pure — unit-tested. */
export function parseImageDataUrl(dataUrl: string): { mime: string; bytes: Uint8Array } | null {
  const m = /^data:(image\/[a-z0-9.+-]+);base64,([A-Za-z0-9+/=\s]+)$/i.exec(dataUrl);
  if (!m) return null;
  try {
    const bytes = decodeStdBase64(m[2].replace(/\s+/g, ""));
    return bytes.length > 0 ? { mime: m[1].toLowerCase(), bytes } : null;
  } catch {
    return null;
  }
}

export function chunkIdFor(imageId: string, index: number): string {
  return `${ID_PREFIX}${imageId}:${index}`;
}

function newImageId(): string {
  const c = globalThis.crypto as { randomUUID?: () => string } | undefined;
  return c?.randomUUID?.() ?? `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`;
}

/**
 * Store a generated image that just arrived on the stream. Returns the
 * reference to put on the message, or null when the payload is unusable or
 * over the cap. The cross-device upload starts in the background and, when it
 * completes, reports back via `onSynced` so the caller can update the
 * reference's `chunkCount` on the persisted message.
 */
export async function storeGeneratedImage(
  dataUrl: string,
  onSynced?: (ref: GeneratedImageRef) => void,
): Promise<GeneratedImageRef | null> {
  const parsed = parseImageDataUrl(dataUrl);
  if (!parsed || parsed.bytes.length > MAX_IMAGE_BYTES) return null;
  const ref: GeneratedImageRef = { id: newImageId(), mime: parsed.mime, size: parsed.bytes.length };
  const stored = await idbPutBytes(IDB, ref.id, parsed.bytes).catch(() => false);
  if (!stored) return null;
  void uploadImage(ref, parsed.bytes)
    .then((chunkCount) => {
      if (chunkCount) onSynced?.({ ...ref, chunkCount });
    })
    .catch(() => {
      /* offline / quota — the image stays device-local; the ref says so */
    });
  return ref;
}

/** Encrypted, chunked upload to the originals collection. Resolves with the
 *  chunk count on success, 0 when the server refused (quota) or no key. */
async function uploadImage(ref: GeneratedImageRef, bytes: Uint8Array): Promise<number> {
  const mk = getMasterKey();
  if (!mk) return 0;
  const sealed = encryptBytes(bytes, deriveOriginalsKey(mk));
  const chunks = chunkBytes(sealed);
  const updatedAt = Date.now();
  for (let i = 0; i < chunks.length; i++) {
    const res = await syncApi.push([
      {
        collection: ORIGINALS_COLLECTION,
        id: chunkIdFor(ref.id, i),
        ciphertext: bytesToBase64(chunks[i]),
        updated_at: updatedAt,
      },
    ]);
    const status = res.results[0]?.status;
    if (status !== "accepted" && status !== "stale") return 0;
  }
  return chunks.length;
}

/**
 * The bytes for a reference: the local store first; otherwise, when the
 * reference says the chunks are on the server, fetch + decrypt + cache them.
 * null when neither is possible (another device generated it and never
 * managed to upload, or offline).
 */
export async function loadGeneratedImage(ref: GeneratedImageRef): Promise<Uint8Array | null> {
  const local = await idbGetBytes(IDB, ref.id).catch(() => null);
  if (local) return local;
  if (!ref.chunkCount) return null;
  const mk = getMasterKey();
  if (!mk) return null;
  try {
    const chunks: Uint8Array[] = [];
    for (let i = 0; i < ref.chunkCount; i++) {
      const blob = await syncApi.blob(ORIGINALS_COLLECTION, chunkIdFor(ref.id, i));
      if (!blob.ciphertext) return null;
      chunks.push(base64ToBytes(blob.ciphertext));
    }
    const bytes = decryptBytes(assembleChunks(chunks), deriveOriginalsKey(mk));
    if (bytes.length !== ref.size) return null;
    void idbPutBytes(IDB, ref.id, bytes).catch(() => false);
    return bytes;
  } catch {
    return null;
  }
}

/** Drop only the local bytes (this device applied another device's deletion —
 *  that device tombstones the server chunks). */
export async function dropLocalGeneratedImage(ref: GeneratedImageRef): Promise<void> {
  await idbDelete(IDB, ref.id).catch(() => undefined);
}

/** Drop the local bytes AND tombstone the server chunks (the chat was deleted
 *  here), so the quota they take is freed on every device. */
export async function deleteGeneratedImage(ref: GeneratedImageRef): Promise<void> {
  await dropLocalGeneratedImage(ref);
  if (!ref.chunkCount) return;
  const now = Date.now();
  try {
    await syncApi.push(
      Array.from({ length: ref.chunkCount }, (_, i) => ({
        collection: ORIGINALS_COLLECTION,
        id: chunkIdFor(ref.id, i),
        ciphertext: "",
        updated_at: now,
        deleted: true,
      })),
    );
  } catch {
    /* offline — the chunks linger until the next delete; acceptable */
  }
}
